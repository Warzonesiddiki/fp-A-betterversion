#!/usr/bin/env node
/**
 * W0.8.1 persistence inventory drift check.
 *
 * Source of truth: src/domain/persistenceAuthority.ts
 * Disk: every `persist({ name: '*-store' })` in src/store
 * Docs: docs/architecture/PERSISTENCE_MAP.md must name every persistKey
 *
 *   node scripts/persistence-map-check.mjs           # check
 *   node scripts/persistence-map-check.mjs --write   # regenerate the map
 */
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const AUTHORITY_PATH = join(ROOT, 'src/domain/persistenceAuthority.ts');
const STORE_DIR = join(ROOT, 'src/store');
const MAP_PATH = join(ROOT, 'docs/architecture/PERSISTENCE_MAP.md');

function persistKeysOnDisk() {
  const keys = new Set();
  for (const file of readdirSync(STORE_DIR)) {
    if (!file.endsWith('.ts') || /\.test\.|\.bench\./.test(file)) continue;
    const text = readFileSync(join(STORE_DIR, file), 'utf8');
    if (!text.includes('persist(')) continue;
    for (const match of text.matchAll(/name:\s*['"]([a-z0-9-]+-store)['"]/g)) {
      keys.add(match[1]);
    }
  }
  return [...keys].sort();
}

function parseRegistry(source) {
  const rows = [];
  const blockRe =
    /\{\s*persistKey:\s*'([^']+)',\s*module:\s*'([^']+)',\s*classification:\s*'([^']+)',\s*authority:\s*'([^']+)',\s*serverRoute:\s*([^,]+),\s*notes:\s*'((?:\\'|[^'])*)'/gs;
  for (const m of source.matchAll(blockRe)) {
    rows.push({
      persistKey: m[1],
      module: m[2],
      classification: m[3],
      authority: m[4],
      serverRoute: m[5].trim(),
      notes: m[6].replace(/\\'/g, "'"),
    });
  }
  return rows;
}

function renderMap(rows) {
  const byClass = {
    'financial-truth': [],
    'user-preference': [],
    'derived-cache': [],
    session: [],
  };
  for (const row of rows) {
    (byClass[row.classification] ?? []).push(row);
  }

  const table = (list) => {
    if (list.length === 0) return '_None._\n';
    const lines = [
      '| persistKey | module | authority | server route | notes |',
      '| --- | --- | --- | --- | --- |',
    ];
    for (const row of list) {
      const route = row.serverRoute === 'null' ? '—' : row.serverRoute.replace(/^'|'$/g, '');
      lines.push(
        `| \`${row.persistKey}\` | \`${row.module}\` | **${row.authority}** | ${route} | ${row.notes} |`
      );
    }
    return lines.join('\n') + '\n';
  };

  const localDraft = rows.filter(
    (r) => r.classification === 'financial-truth' && r.authority === 'local-draft'
  ).length;
  const serverAuth = rows.filter(
    (r) => r.classification === 'financial-truth' && r.authority === 'server'
  ).length;

  return `# PERSISTENCE MAP (W0.8.1)

> Generated by \`scripts/persistence-map-check.mjs\`. **Do not hand-edit.**
> Source of truth: \`src/domain/persistenceAuthority.ts\`.
> Drift against \`persist()\` keys in \`src/store\` fails CI (\`npm run persistence:map\`).

**Measured ${new Date().toISOString().slice(0, 10)}.** ${rows.length} persisted Zustand stores.

| Classification | Count | Authority rule |
| --- | --- | --- |
| financial-truth | ${byClass['financial-truth'].length} | Server must be SoR. Today **${localDraft} local-draft**, **${serverAuth} server**. |
| user-preference | ${byClass['user-preference'].length} | Local is legitimate. |
| derived-cache | ${byClass['derived-cache'].length} | Rebuildable; never the system of record (ST2). |
| session | ${byClass['session'].length} | Tokens; not financial truth. |

**Honesty (R-21).** Clearing site data destroys every \`local-draft\` financial-truth store.
No backup, RTO, or audit claim is valid for those rows. The UI states this
(\`DurabilityBanner\`, W0.8.5). The W0.8.6 spike makes \`gl-store\` server-authoritative
after tenancy (W0.2).

## financial-truth

${table(byClass['financial-truth'])}

## derived-cache

${table(byClass['derived-cache'])}

## user-preference

${table(byClass['user-preference'])}

## session

${table(byClass['session'])}

## Authority legend

| Value | Meaning |
| --- | --- |
| \`server\` | Control Plane is the system of record. Client is a replica/cache. |
| \`local-draft\` | Client copy is a **draft**. Must be labelled. Not official. |
| \`local\` | Local is the legitimate authority (preferences, session). |
`;
}

const source = readFileSync(AUTHORITY_PATH, 'utf8');
const rows = parseRegistry(source);
const disk = persistKeysOnDisk();
const registered = rows.map((r) => r.persistKey).sort();

const failures = [];
if (rows.length === 0) {
  failures.push('Failed to parse PERSISTED_STORES from persistenceAuthority.ts');
}

const missingOnDisk = registered.filter((k) => !disk.includes(k));
const missingInRegistry = disk.filter((k) => !registered.includes(k));
if (missingOnDisk.length) {
  failures.push(`Registry keys with no persist() on disk: ${missingOnDisk.join(', ')}`);
}
if (missingInRegistry.length) {
  failures.push(`persist() keys missing from the registry: ${missingInRegistry.join(', ')}`);
}

const generated = renderMap(rows);

if (process.argv.includes('--write')) {
  writeFileSync(MAP_PATH, generated);
  console.log(`Wrote ${MAP_PATH} (${rows.length} stores).`);
}

let existing = '';
try {
  existing = readFileSync(MAP_PATH, 'utf8');
} catch {
  failures.push('docs/architecture/PERSISTENCE_MAP.md is missing. Run with --write.');
}

if (existing) {
  for (const key of registered) {
    if (!existing.includes('`' + key + '`')) {
      failures.push(`PERSISTENCE_MAP.md does not mention persistKey ${key}`);
    }
  }
}

console.log(`Persistence inventory: ${disk.length} persist() stores, ${rows.length} registered.`);

if (failures.length) {
  console.error('\nPERSISTENCE MAP DRIFT:\n');
  for (const f of failures) console.error(`  ✗ ${f}`);
  console.error('\n  Fix: update src/domain/persistenceAuthority.ts, then');
  console.error('       node scripts/persistence-map-check.mjs --write');
  process.exit(1);
}

console.log('✓ Persistence map matches persist() keys and the authority registry.');
